const FALLBACK: LucideIcon = Sparkles;

export function getIcon(name: string): LucideIcon {
  return ICONS[name] ?? FALLBACK;
}

export type { LucideIcon };

/**
 * Renders a catalogue icon by name.
 *
 * The lookup is a static module-level map, so the resolved component reference
 * is stable across renders; going through `createElement` keeps the React
 * Compiler from treating it as a component created during render.
 */
export function ToolIcon({ name, className }: { name: string; className?: string }) {
  return React.createElement(getIcon(name), { className, "aria-hidden": true });
}
